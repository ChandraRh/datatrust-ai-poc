"""PostgreSQL-backed lifecycle state for ADLS pipeline batches."""
from __future__ import annotations

import psycopg
from psycopg.rows import dict_row

import config


def connect():
    return psycopg.connect(
        sslmode=config.PG_SSLMODE,
        host=config.PG_HOST,
        port=config.PG_PORT,
        dbname=config.PG_DATABASE,
        user=config.PG_USER,
        password=config.PG_PASSWORD,
        row_factory=dict_row,
        connect_timeout=5,
    )


def ensure_table() -> None:
    with connect() as conn:
        conn.execute("CREATE SCHEMA IF NOT EXISTS audit")
        conn.execute("""
            CREATE TABLE IF NOT EXISTS audit.adls_batch_runs (
                batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                batch_folder TEXT NOT NULL UNIQUE,
                batch_name TEXT NOT NULL,
                status TEXT NOT NULL CHECK (status IN ('READY', 'RUNNING', 'SUCCEEDED', 'FAILED')),
                attempt_count INTEGER NOT NULL DEFAULT 0,
                first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                started_at TIMESTAMPTZ,
                finished_at TIMESTAMPTZ,
                last_error TEXT,
                pipeline_batch_id TEXT,
                retry_requested_by TEXT
            )
        """)


def register_batch(folder: str, name: str, legacy_state: str | None = None) -> dict:
    initial_status = {"processed": "SUCCEEDED", "failed": "FAILED"}.get(legacy_state, "READY")
    legacy_error = (
        "Previous worker marked this batch failed. See the pipeline log for details."
        if initial_status == "FAILED"
        else None
    )
    with connect() as conn:
        conn.execute(
            """INSERT INTO audit.adls_batch_runs (batch_folder, batch_name, status, last_error)
               VALUES (%s, %s, %s, %s) ON CONFLICT (batch_folder) DO NOTHING""",
            (folder, name, initial_status, legacy_error),
        )
        row = conn.execute(
            "SELECT * FROM audit.adls_batch_runs WHERE batch_folder = %s", (folder,)
        ).fetchone()
    if row is None:
        raise RuntimeError(f"Could not register ADLS batch {folder}")
    return row


def list_batches(limit: int = 50) -> list[dict]:
    limit = min(max(int(limit), 1), 200)
    with connect() as conn:
        return conn.execute(
            """SELECT batch_id, batch_folder, batch_name, status, attempt_count, first_seen_at,
                      updated_at, started_at, finished_at, last_error, pipeline_batch_id,
                      retry_requested_by
               FROM audit.adls_batch_runs
               ORDER BY first_seen_at DESC, batch_id DESC LIMIT %s""",
            (limit,),
        ).fetchall()


def ready_batches() -> list[dict]:
    with connect() as conn:
        return conn.execute(
            """SELECT batch_id, batch_folder, batch_name
               FROM audit.adls_batch_runs WHERE status = 'READY'
               ORDER BY first_seen_at, batch_id"""
        ).fetchall()


def get_batch(batch_id: int) -> dict | None:
    with connect() as conn:
        return conn.execute(
            "SELECT * FROM audit.adls_batch_runs WHERE batch_id = %s", (batch_id,)
        ).fetchone()


def get_batch_by_folder(folder: str) -> dict | None:
    with connect() as conn:
        return conn.execute(
            "SELECT * FROM audit.adls_batch_runs WHERE batch_folder = %s", (folder,)
        ).fetchone()


def claim_batch(folder: str) -> dict | None:
    with connect() as conn:
        return conn.execute(
            """UPDATE audit.adls_batch_runs
               SET status = 'RUNNING', attempt_count = attempt_count + 1,
                   started_at = now(), finished_at = NULL, updated_at = now(), last_error = NULL
               WHERE batch_folder = %s AND status = 'READY'
               RETURNING batch_id, batch_folder, batch_name, attempt_count, started_at""",
            (folder,),
        ).fetchone()


def finish_batch(batch_id: int, status: str, error: str | None = None,
                 pipeline_batch_id: str | None = None) -> None:
    if status not in {"SUCCEEDED", "FAILED"}:
        raise ValueError(f"Unsupported terminal batch status: {status}")
    with connect() as conn:
        row = conn.execute(
            """UPDATE audit.adls_batch_runs
               SET status = %s, last_error = %s, pipeline_batch_id = %s,
                   finished_at = now(), updated_at = now()
               WHERE batch_id = %s AND status = 'RUNNING'
               RETURNING batch_id""",
            (status, error, pipeline_batch_id, batch_id),
        ).fetchone()
    if row is None:
        raise RuntimeError(f"Batch {batch_id} was not RUNNING when its result was recorded")


def request_retry(batch_id: int, requested_by: str) -> dict:
    with connect() as conn:
        row = conn.execute(
            """UPDATE audit.adls_batch_runs
               SET status = 'READY', finished_at = NULL, updated_at = now(), retry_requested_by = %s
               WHERE batch_id = %s AND status = 'FAILED'
               RETURNING batch_id, batch_folder, batch_name, status""",
            (requested_by, batch_id),
        ).fetchone()
    if row is None:
        current = get_batch(batch_id)
        if current is None:
            raise ValueError("Batch not found.")
        raise ValueError(f"Only failed batches can be retried; this batch is {current['status']}.")
    return row


def retry_failed_upload(folder: str, requested_by: str = "upload_to_adls.py") -> dict | None:
    batch = get_batch_by_folder(folder)
    if batch is None:
        return None
    if batch["status"] == "FAILED":
        return request_retry(batch["batch_id"], requested_by)
    return batch


def fail_interrupted_batches() -> int:
    with connect() as conn:
        rows = conn.execute(
            """UPDATE audit.adls_batch_runs
               SET status = 'FAILED', finished_at = now(), updated_at = now(),
                   last_error = 'Worker restarted while this batch was running. Retry it after checking the pipeline log.'
               WHERE status = 'RUNNING' RETURNING batch_id"""
        ).fetchall()
    return len(rows)


def latest_pipeline_error(since, pipeline_batch_id: str | None = None) -> str | None:
    if pipeline_batch_id:
        query = """SELECT layer, pipeline_id, error_type, error_message
                   FROM audit.error_log
                   WHERE logged_at >= %s AND batch_id = %s AND status IN ('FAILED', 'CANCELLED')
                   ORDER BY error_id DESC LIMIT 1"""
        params = (since, pipeline_batch_id)
    else:
        query = """SELECT layer, pipeline_id, error_type, error_message
                   FROM audit.error_log
                   WHERE logged_at >= %s AND batch_id IS NULL AND status IN ('FAILED', 'CANCELLED')
                   ORDER BY error_id DESC LIMIT 1"""
        params = (since,)
    with connect() as conn:
        row = conn.execute(query, params).fetchone()
    if not row:
        return None
    prefix = " / ".join(part for part in (row["layer"], row["pipeline_id"], row["error_type"]) if part)
    message = row["error_message"] or "Pipeline step failed."
    return f"{prefix}: {message}"[:2000]


def latest_pipeline_batch(since) -> str | None:
    with connect() as conn:
        row = conn.execute(
            """SELECT batch_id FROM audit.batch_control
               WHERE started_at >= %s ORDER BY started_at DESC LIMIT 1""",
            (since,),
        ).fetchone()
    return row["batch_id"] if row else None
